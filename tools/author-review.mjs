#!/usr/bin/env node
// tools/author-review.mjs
// Aggregate every [FOR THE AUTHOR] flag in a project into ONE review file, with a
// source pointer (file:line + section) for each. Dependency-free (runs in bare worktrees).
//
//   node tools/author-review.mjs <projectKey>      # regenerate one project's review file
//   node tools/author-review.mjs --all             # regenerate every project's file
//   node tools/author-review.mjs <projectKey> --print   # print to stdout, don't write
//
// Projects are defined in tools/author-review.projects.json. Each project keeps its own
// separate list — books and games never mix. Add a project by adding a config entry.

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const CONFIG = path.join(ROOT, 'tools', 'author-review.projects.json');
const MARKER = /\[FOR THE AUTHOR\]/i;

function walk(dir, acc) {
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return acc; }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === '_archive' || e.name === '.git') continue;
      walk(p, acc);
    } else if (e.isFile() && e.name.endsWith('.md')) acc.push(p);
  }
  return acc;
}

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

// Capture the flag as readable text. Three shapes:
//  - marker on a SECTION HEADER (e.g. "## [FOR THE AUTHOR] — held changes") → the flags are
//    the section BODY, so capture the title + the lines beneath it until the next header.
//  - marker in a TABLE ROW → that row.
//  - marker inline in prose → the line plus its paragraph continuation.
function extract(lines, i) {
  const first = lines[i];
  const hm = first.match(/^(#{1,6})\s+(.*)/);
  if (hm) {
    const level = hm[1].length;
    const body = [];
    for (let j = i + 1; j < lines.length && body.length < 12; j++) {
      const h2 = lines[j].match(/^(#{1,6})\s/);
      if (h2 && h2[1].length <= level) break;     // next section of same-or-higher level
      if (lines[j].trim() !== '') body.push(lines[j].trim());
    }
    return body.length ? `${hm[2].trim()} — ${body.join(' ')}` : hm[2].trim();
  }
  if (first.trimStart().startsWith('|')) {
    return first.trim().replace(/^\|/, '').replace(/\|$/, '').replace(/\s*\|\s*/g, ' · ').trim();
  }
  const out = [first.trim()];
  for (let j = i + 1; j < lines.length && out.length < 6; j++) {
    const l = lines[j];
    if (l.trim() === '' || /^#{1,6}\s/.test(l) || /^\s*([-*]|\d+\.)\s/.test(l) || l.trimStart().startsWith('|')) break;
    out.push(l.trim());
  }
  return out.join(' ');
}

function scanFile(file) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  const found = [];
  const seen = new Set();
  let section = '', prevSection = '';
  for (let i = 0; i < lines.length; i++) {
    const h = lines[i].match(/^#{1,6}\s+(.*)/);
    if (h) { prevSection = section; section = h[1].trim(); }
    if (MARKER.test(lines[i])) {
      const isHeader = /^#{1,6}\s/.test(lines[i]);
      let text = extract(lines, i).replace(/\s+/g, ' ').trim();
      if (text.length > 500) text = text.slice(0, 500).trimEnd() + ' …';
      const key = text.toLowerCase();
      if (seen.has(key)) continue;      // drop exact duplicates within a file
      seen.add(key);
      found.push({ line: i + 1, section: isHeader ? prevSection : section, text });
    }
  }
  return found;
}

function keep(relPath, project) {
  if (relPath === project.out) return false;
  if (project.exclude) for (const ex of project.exclude) if (relPath.includes(ex)) return false;
  if (project.include && project.include.length) return project.include.some((inc) => relPath.includes(inc));
  return true;
}

function render(project, byFile, total, dateStr) {
  const L = [];
  L.push(`# ${project.title} — Author Review Queue`);
  L.push('');
  L.push(`_${total} open \`[FOR THE AUTHOR]\` flag(s) across ${byFile.length} file(s). Generated by \`node tools/author-review.mjs ${project.key}\` on ${dateStr}._`);
  L.push('');
  L.push(`_Regenerated file — don't hand-edit. Resolve a flag in its **source doc** (or record the decision in the project bible), then re-run to refresh._`);
  L.push('');
  if (!total) { L.push('No open flags. 🎉'); return L.join('\n') + '\n'; }
  L.push('| Source | Flags |');
  L.push('|---|--:|');
  for (const f of byFile) L.push(`| [${f.file}](${f.file}) | ${f.items.length} |`);
  L.push('');
  for (const f of byFile) {
    L.push(`## ${f.file} — ${f.items.length}`);
    L.push('');
    for (const it of f.items) {
      const sec = it.section ? ` · _${it.section}_` : '';
      L.push(`- [\`${f.file}:${it.line}\`](${f.file}#L${it.line})${sec}`);
      L.push(`  ${it.text}`);
    }
    L.push('');
  }
  return L.join('\n') + '\n';
}

function runProject(project, opts) {
  const files = [];
  for (const root of project.roots) walk(path.join(ROOT, root), files);
  const byFile = [];
  let total = 0;
  for (const file of files.sort()) {
    const r = rel(file);
    if (!keep(r, project)) continue;
    const items = scanFile(file);
    if (items.length) { byFile.push({ file: r, items }); total += items.length; }
  }
  const dateStr = new Date().toISOString().slice(0, 10);
  const md = render(project, byFile, total, dateStr);
  if (opts.print) process.stdout.write(md);
  else {
    fs.mkdirSync(path.dirname(path.join(ROOT, project.out)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, project.out), md);
  }
  return { total, files: byFile.length, out: project.out };
}

const args = process.argv.slice(2);
const print = args.includes('--print');
const all = args.includes('--all');
const key = args.find((a) => !a.startsWith('--'));

let projects;
try { projects = JSON.parse(fs.readFileSync(CONFIG, 'utf8')); }
catch (e) { console.error(`Cannot read ${rel(CONFIG)}: ${e.message}`); process.exit(1); }

if (!all && !key) {
  console.error('Usage: node tools/author-review.mjs <projectKey> | --all [--print]');
  console.error('Projects: ' + projects.map((p) => p.key).join(', '));
  process.exit(1);
}
const targets = all ? projects : projects.filter((p) => p.key === key);
if (!targets.length) {
  console.error(`No project "${key}". Known: ${projects.map((p) => p.key).join(', ')}`);
  process.exit(1);
}
for (const p of targets) {
  const res = runProject(p, { print });
  if (!print) console.log(`[${p.key}] ${res.total} flag(s) across ${res.files} file(s) -> ${res.out}`);
}
